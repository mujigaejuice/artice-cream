-- Streak reward (credit policy P4). Ships disabled: streak_enabled=false and
-- streak_counts_from=null, so no completion date counts and nothing is granted.
-- Streak credits are NOT added to get_quiz_spendable_balance: the shop keeps
-- spending only first-quiz-completion rewards (article_read, quiz_bonus,
-- welcome) as decided in 20261026071437_quiz_only_spending.sql.
begin;

alter table public.credit_policy
  add column streak_enabled boolean not null default false,
  add column streak_counts_from date,
  add column streak_reward integer not null default 50 check (streak_reward > 0),
  add constraint credit_policy_streak_start_check
    check (not streak_enabled or streak_counts_from is not null);

-- Turning the streak on, or changing its amount, is a new policy version.
-- The counting start may move later (to skip a paused period) but never earlier,
-- so a later update cannot start counting older completion dates.
create function public.guard_credit_streak_policy()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  if new.streak_enabled and not old.streak_enabled and new.version <= old.version then
    raise exception 'streak activation requires a new policy version' using errcode = '22023';
  end if;
  if new.streak_reward <> old.streak_reward and new.version <= old.version then
    raise exception 'streak reward change requires a new policy version' using errcode = '22023';
  end if;
  if old.streak_counts_from is not null and (new.streak_counts_from is null
      or new.streak_counts_from < old.streak_counts_from) then
    raise exception 'streak count start cannot move earlier' using errcode = '22023';
  end if;
  return new;
end;
$$;
create trigger guard_credit_streak_policy before update on public.credit_policy
  for each row execute function public.guard_credit_streak_policy();

-- Recreate the ledger checks with 'streak' (positive amount). The original
-- constraint names were generated by PostgreSQL, so locate them by definition.
do $$
declare v_name text;
begin
  for v_name in select conname from pg_constraint
    where conrelid = 'public.credit_events'::regclass and contype = 'c'
      and pg_get_constraintdef(oid) like '%reason%'
  loop
    execute format('alter table public.credit_events drop constraint %I', v_name);
  end loop;
end;
$$;
alter table public.credit_events
  add constraint credit_events_reason_check check (reason in
    ('article_read', 'quiz_bonus', 'welcome', 'streak', 'purchase', 'adjustment')),
  add constraint credit_events_amount_check check (
    (reason in ('article_read', 'welcome', 'streak') and amount > 0)
    or (reason = 'quiz_bonus' and amount >= 0)
    or (reason = 'purchase' and amount < 0)
    or (reason = 'adjustment' and amount <> 0));

-- Runs of consecutive KST dates with a first completion. completed_at is only
-- written on the started -> completed transition, so reviews never add a date
-- and several completions on one date count once.
create function public.credit_streak_runs(p_user_id uuid, p_from date, p_to date)
returns table(run_start date, run_end date, run_days integer)
language sql stable security invoker set search_path = '' as $$
  with days as (
    select distinct (p.completed_at at time zone 'Asia/Seoul')::date as day
    from public.user_article_progress p
    where p.user_id = p_user_id and p.status in ('completed', 'saved')
      and p.completed_at >= (p_from::timestamp at time zone 'Asia/Seoul')
      and p.completed_at < ((p_to + 1)::timestamp at time zone 'Asia/Seoul')
  ), grouped as (
    select day, day - (row_number() over (order by day))::integer as grp from days
  )
  select min(day), max(day), count(*)::integer from grouped group by grp;
$$;

-- Pays +streak_reward when the completion at p_now closes day 7, 14, 21... of
-- the run ending on that KST date. The ledger key makes retries and concurrent
-- calls grant at most once. Called inside grade_quiz_with_credits, whose
-- profile row lock already serializes a user's completions.
create function public.grant_credit_streak(p_user_id uuid, p_article_id bigint, p_now timestamptz)
returns integer language plpgsql security invoker set search_path = '' as $$
declare
  v_policy public.credit_policy%rowtype;
  v_today date := (p_now at time zone 'Asia/Seoul')::date;
  v_start date;
  v_days integer;
  v_block integer;
begin
  perform id from public.profiles where id = p_user_id for update;
  if not found then return 0; end if;
  select * into strict v_policy from public.credit_policy where id = 1 for share;
  if not v_policy.streak_enabled or v_policy.earning_mode <> 'active'
     or v_policy.starts_at is null or p_now < v_policy.starts_at
     or v_today < v_policy.streak_counts_from then
    return 0;
  end if;
  select r.run_start, r.run_days into v_start, v_days
    from public.credit_streak_runs(p_user_id, v_policy.streak_counts_from, v_today) r
    where r.run_end = v_today;
  if not found or v_days % 7 <> 0 then return 0; end if;
  v_block := v_days / 7;
  insert into public.credit_events (user_id, amount, reason, source_id, policy_version, metadata)
    values (p_user_id, v_policy.streak_reward, 'streak',
      'streak:' || to_char(v_start, 'YYYY-MM-DD') || ':' || v_block, v_policy.version,
      jsonb_build_object('articleId', p_article_id, 'runStart', to_char(v_start, 'YYYY-MM-DD'),
        'block', v_block, 'days', v_days))
    on conflict (user_id, reason, source_id) do nothing;
  if not found then return 0; end if;
  return v_policy.streak_reward;
end;
$$;

-- Display state: the latest run since streak_counts_from. The API reports 0
-- days when lastDay is older than yesterday (KST).
create function public.get_credit_streak(p_user_id uuid)
returns jsonb language sql stable security invoker set search_path = '' as $$
  select jsonb_build_object(
    'enabled', p.streak_enabled and p.earning_mode = 'active',
    'reward', p.streak_reward, 'blockDays', 7,
    'days', coalesce(r.run_days, 0), 'lastDay', to_char(r.run_end, 'YYYY-MM-DD'))
  from public.credit_policy p
  left join lateral (
    select * from public.credit_streak_runs(p_user_id, p.streak_counts_from,
      (now() at time zone 'Asia/Seoul')::date)
    order by run_end desc limit 1
  ) r on p.streak_enabled and p.earning_mode = 'active'
  where p.id = 1;
$$;

-- get_credit_result and grade_quiz_with_credits are copied from
-- 20261025145740_credits_core.sql; only the v_streak lines are new.
create or replace function public.get_credit_result(p_user_id uuid, p_article_id bigint)
returns jsonb language plpgsql volatile security invoker set search_path = '' as $$
declare
  v_balance bigint;
  v_base integer := 0;
  v_bonus integer := 0;
  v_welcome integer := 0;
  v_streak integer := 0;
  v_version integer;
  v_exists boolean;
begin
  select coalesce(sum(amount), 0) into v_balance from public.credit_events where user_id = p_user_id;
  select amount, policy_version into v_base, v_version from public.credit_events
    where user_id = p_user_id and reason = 'article_read' and source_id = 'article:' || p_article_id::text;
  v_exists := found;
  select coalesce(amount, 0) into v_bonus from public.credit_events
    where user_id = p_user_id and reason = 'quiz_bonus' and source_id = 'article:' || p_article_id::text;
  select coalesce(amount, 0) into v_welcome from public.credit_events
    where user_id = p_user_id and reason = 'welcome' and source_id = 'account'
      and metadata->>'articleId' = p_article_id::text;
  select coalesce(sum(amount), 0) into v_streak from public.credit_events
    where user_id = p_user_id and reason = 'streak'
      and metadata->>'articleId' = p_article_id::text;
  if v_version is null then select version into v_version from public.credit_policy where id = 1; end if;
  return jsonb_build_object(
    'status', case when v_exists then 'already_granted' else 'not_eligible' end,
    'newlyGranted', 0, 'articleReward', jsonb_build_object(
      'base', coalesce(v_base, 0), 'bonus', coalesce(v_bonus, 0),
      'total', coalesce(v_base, 0) + coalesce(v_bonus, 0)),
    'welcomeReward', coalesce(v_welcome, 0), 'streakReward', v_streak, 'balance', v_balance,
    'policyVersion', v_version
  );
end;
$$;

create or replace function public.grade_quiz_with_credits(p_user_id uuid, p_variant_id bigint, p_answers jsonb)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  v_policy public.credit_policy%rowtype;
  v_variant public.article_variants%rowtype;
  v_article public.articles%rowtype;
  v_progress public.user_article_progress%rowtype;
  v_level public.user_domain_levels%rowtype;
  v_question public.quiz_questions%rowtype;
  v_domain public.domains%rowtype;
  v_now timestamptz;
  v_review jsonb := '[]'::jsonb;
  v_total integer := 0;
  v_correct integer := 0;
  v_keys integer;
  v_answer_text text;
  v_answer integer;
  v_score real;
  v_scores real[];
  v_rolling real;
  v_prev integer;
  v_next integer;
  v_dir text := '유지';
  v_is_review boolean;
  v_bonus integer;
  v_welcome integer := 0;
  v_streak integer := 0;
  v_newly integer := 0;
  v_credits jsonb;
begin
  if p_variant_id is null or p_variant_id <= 0 or jsonb_typeof(p_answers) <> 'object' then
    return jsonb_build_object('error', 'invalid body');
  end if;
  perform id from public.profiles where id = p_user_id for update;
  if not found then return jsonb_build_object('error', 'unauthenticated'); end if;
  select * into strict v_policy from public.credit_policy where id = 1 for share;

  select * into v_variant from public.article_variants where id = p_variant_id for share;
  if not found then return jsonb_build_object('error', 'not found'); end if;
  select * into v_article from public.articles where id = v_variant.article_id for share;
  if not found then return jsonb_build_object('error', 'not found'); end if;
  perform source from public.content_source_rights where source = v_article.source for share;
  if not public.content_article_allows(v_article.id, 'publish') then
    return jsonb_build_object('error', 'not found');
  end if;
  select * into v_domain from public.domains where id = v_article.domain_id;
  if not found then return jsonb_build_object('error', 'not found'); end if;

  for v_question in select * from public.quiz_questions where variant_id = p_variant_id order by id for share loop
    v_total := v_total + 1;
    v_answer_text := p_answers->>v_question.id::text;
    if v_answer_text is null or v_answer_text !~ '^[0-9]{1,2}$'
       or jsonb_typeof(p_answers->v_question.id::text) <> 'number' then
      return jsonb_build_object('error', 'incomplete');
    end if;
    v_answer := v_answer_text::integer;
    if v_answer >= jsonb_array_length(v_question.options) then
      return jsonb_build_object('error', 'incomplete');
    end if;
    if v_answer = v_question.correct_index then v_correct := v_correct + 1; end if;
    v_review := v_review || jsonb_build_array(jsonb_build_object(
      'questionId', v_question.id, 'prompt', v_question.prompt,
      'options', v_question.options, 'picked', v_answer,
      'correct_index', v_question.correct_index,
      'correct', v_answer = v_question.correct_index,
      'explanation', v_question.explanation));
  end loop;
  if v_total = 0 then return jsonb_build_object('error', 'no questions'); end if;
  select count(*) into v_keys from jsonb_object_keys(p_answers);
  if v_keys <> v_total then return jsonb_build_object('error', 'invalid body'); end if;
  v_score := v_correct::real / v_total::real;

  select * into v_progress from public.user_article_progress
    where user_id = p_user_id and article_id = v_article.id for update;
  if not found then return jsonb_build_object('error', 'article not opened'); end if;
  v_is_review := v_progress.status in ('completed', 'saved');
  if v_progress.status not in ('started', 'completed', 'saved') then
    return jsonb_build_object('error', 'invalid progress');
  end if;

  if not v_is_review then
    if v_policy.earning_mode = 'paused' then
      return jsonb_build_object('error', 'credits temporarily unavailable');
    end if;
    v_now := clock_timestamp();
    perform set_config('app.credit_writer', 'v1', true);
    if v_article.content_kind <> 'original' then
      select * into v_level from public.user_domain_levels
        where user_id = p_user_id and domain_id = v_article.domain_id for update;
      if found then
        v_prev := greatest(1, least(3, v_level.level));
        v_scores := coalesce(v_level.recent_scores, '{}'::real[]);
      else
        v_prev := greatest(1, least(3, v_variant.level));
        v_scores := '{}'::real[];
      end if;
      v_scores := v_scores || v_score;
      if cardinality(v_scores) > 3 then
        v_scores := v_scores[cardinality(v_scores)-2:cardinality(v_scores)];
      end if;
      select avg(value)::real into v_rolling from unnest(v_scores) as value;
      v_next := v_prev;
      if v_rolling >= 0.75 and v_prev < 3 then
        v_next := v_prev + 1;
        v_dir := '상승';
      elsif v_rolling <= 0.4 and v_prev > 1 then
        v_next := v_prev - 1;
        v_dir := '하강';
      end if;
      insert into public.user_domain_levels
        (user_id, domain_id, level, rolling_accuracy, quizzes_taken, recent_scores, updated_at)
        values (p_user_id, v_article.domain_id, v_next, v_rolling,
          coalesce(v_level.quizzes_taken, 0) + 1, v_scores, v_now)
        on conflict (user_id, domain_id) do update set
          level = excluded.level, rolling_accuracy = excluded.rolling_accuracy,
          quizzes_taken = excluded.quizzes_taken, recent_scores = excluded.recent_scores,
          updated_at = excluded.updated_at;
    end if;
    update public.user_article_progress set status = 'completed', variant_id = p_variant_id,
      quiz_score = v_score, quiz_answers = p_answers, completed_at = v_now
      where id = v_progress.id and status = 'started';
    if not found then raise exception 'progress changed during grading' using errcode = '40001'; end if;

    if v_policy.earning_mode = 'active' and v_now >= v_policy.starts_at then
      v_bonus := round(v_correct::numeric * v_policy.quiz_bonus_max / v_total)::integer;
      insert into public.credit_events (user_id, amount, reason, source_id, policy_version, metadata)
        values (p_user_id, v_policy.article_reward, 'article_read',
          'article:' || v_article.id, v_policy.version,
          jsonb_build_object('articleId', v_article.id, 'variantId', p_variant_id,
            'correct', v_correct, 'total', v_total));
      insert into public.credit_events (user_id, amount, reason, source_id, policy_version, metadata)
        values (p_user_id, v_bonus, 'quiz_bonus', 'article:' || v_article.id, v_policy.version,
          jsonb_build_object('articleId', v_article.id, 'variantId', p_variant_id,
            'correct', v_correct, 'total', v_total));
      if not exists (select 1 from public.credit_events
        where user_id = p_user_id and reason = 'welcome' and source_id = 'account') then
        v_welcome := v_policy.welcome_reward;
        insert into public.credit_events (user_id, amount, reason, source_id, policy_version, metadata)
          values (p_user_id, v_welcome, 'welcome', 'account', v_policy.version,
            jsonb_build_object('articleId', v_article.id));
      end if;
      v_streak := public.grant_credit_streak(p_user_id, v_article.id, v_now);
      v_newly := v_policy.article_reward + v_bonus + v_welcome + v_streak;
    end if;
  end if;

  v_credits := public.get_credit_result(p_user_id, v_article.id);
  if not v_is_review then
    v_credits := v_credits || jsonb_build_object(
      'status', case when v_newly > 0 then 'granted' else 'disabled' end,
      'newlyGranted', v_newly);
  end if;
  return jsonb_build_object(
    'score', v_score, 'correct', v_correct, 'total', v_total, 'review', v_review,
    'prevLevel', case when v_is_review then null else v_prev end,
    'newLevel', case when v_is_review then null else v_next end,
    'dir', case when v_is_review then '유지' else v_dir end,
    'rollingAccuracy', case when v_is_review then null else v_rolling end,
    'domain', v_domain.slug, 'domainLabel', v_domain.name_ko,
    'articleId', v_article.id, 'variantId', p_variant_id,
    'isOriginal', v_article.content_kind = 'original', 'isReview', v_is_review,
    'canSave', v_progress.status = 'completed' or (not v_is_review),
    'sourceUrl', v_article.source_url, 'credits', v_credits
  );
end;
$$;

create or replace function public.get_credit_snapshot(p_user_id uuid)
returns jsonb language sql stable security invoker set search_path = '' as $$
  select jsonb_build_object(
    'balance', coalesce((select sum(e.amount) from public.credit_events e
      where e.user_id = p_user_id), 0)::text,
    'spendableBalance', public.get_quiz_spendable_balance(p_user_id)::text,
    'policyVersion', p.version,
    'earningMode', p.earning_mode,
    'spendingEnabled', p.spending_enabled,
    'hasWelcome', exists (select 1 from public.credit_events e
      where e.user_id = p_user_id and e.reason = 'welcome' and e.source_id = 'account'),
    'rules', jsonb_build_object('article', p.article_reward,
      'quizBonusMax', p.quiz_bonus_max, 'welcome', p.welcome_reward),
    'streak', public.get_credit_streak(p_user_id)
  ) || public.get_cosmetic_state(p_user_id)
  from public.credit_policy p
  where p.id = 1 and exists (select 1 from public.profiles where id = p_user_id);
$$;

